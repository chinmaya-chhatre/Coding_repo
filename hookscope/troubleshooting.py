"""The signature troubleshooting guide, generated from the detector registry.

``python -m hookscope.troubleshooting`` rewrites ``docs/troubleshooting.md``. A test fails when the file
is out of date, so adding a detector (or a cause) means adding its entry to ``CAUSE_HELP`` and
regenerating, and the guide cannot drift from what HookScope actually reports.
"""

from __future__ import annotations

from pathlib import Path

from .diagnostics import CAUSE_HELP, DETECTORS
from .providers import PROVIDERS

GUIDE = Path(__file__).resolve().parent.parent / "docs" / "troubleshooting.md"


def _title(name: str) -> str:
    return name.replace("_", " ").capitalize()


def render() -> str:
    """The guide as Markdown: how to read a failed delivery, then every detector and its causes in order."""
    lines = [
        "# Why did a signature check fail?",
        "",
        "<!-- Generated by `python -m hookscope.troubleshooting`: edit CAUSE_HELP, not this file. -->",
        "",
        "When a delivery is rejected (`invalid` or `unsigned`), HookScope runs a list of small detectors "
        "over it and stores the first one that recognises the problem as the event's **diagnosis**: "
        "a `cause`, "
        "a one-sentence `message` and a one-sentence `fix`. You see it in the **Why did this fail?** panel "
        "on the dashboard, in the `401` answer, in `GET /api/events/{id}`, and counted in the "
        "`hookscope_signature_failures_total{source,cause}` metric.",
        "",
        "The detectors run in the order below, so a specific cause is reported before a general one. "
        "`no_secret` (no secret configured) is not a failure of the sender and is not diagnosed.",
        "",
        "| Cause | Detector | What it means |",
        "|---|---|---|",
    ]
    for detector in DETECTORS:
        for cause in getattr(detector, "causes", ()):
            title = CAUSE_HELP[cause][0]
            lines.append(f"| `{cause}` | `{detector.__name__}` | {title} |")
    lines.append("")
    for detector in DETECTORS:
        causes = getattr(detector, "causes", ())
        summary = (detector.__doc__ or "").strip().splitlines()[0] if detector.__doc__ else ""
        lines += [f"## {_title(detector.__name__)}", ""]
        if summary:
            lines += [summary.replace("``", "`"), ""]
        for cause in causes:
            title, meaning, fix = CAUSE_HELP[cause]
            lines += [f"### `{cause}`: {title}", "", meaning, "", f"**Fix:** {fix}", ""]
    lines += [
        "## Where each provider's signature lives",
        "",
        "| Provider | Header | Digest | Timestamp | Signs the URL |",
        "|---|---|---|---|---|",
    ]
    for name, provider in PROVIDERS.items():
        encoding, algorithm = provider.signature_form or ("", "")
        form = f"{algorithm}, {encoding}" if algorithm else ""
        stamp = "yes" if provider.timestamp_from else "no"
        url = "yes" if provider.url_signed else "no"
        lines.append(f"| `{name}` | `{provider.signature_header}` | {form} | {stamp} | {url} |")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    GUIDE.write_text(render())
    print(f"wrote {GUIDE}")
